/* =====================================================================
 * 002_create_role_qc_data_manager.sql
 * Scope : per-database (run against EACH of dataloggingDev / dataloggingTest)
 * Effect: create role [qc_data_manager_role] and grant it READ-ONLY access to
 *         the [qc] schema. Writes are NOT granted directly -- they will happen
 *         only through stored procedures granted EXECUTE individually (later, as
 *         a new migration once the procedures exist).
 * Safe to re-run (idempotent). Records itself in the ledger. Run 001 first.
 *
 * Single batch on purpose (see 001 for why).
 * ===================================================================== */

IF DB_NAME() NOT IN (N'dataloggingDev', N'dataloggingTest')
    THROW 50000, N'Refusing to run: not a datalogging database.', 1;
IF OBJECT_ID(N'[qc].[schema_migrations]', N'U') IS NULL
    THROW 50000, N'Run 001 first (creates the qc schema + ledger).', 1;

IF NOT EXISTS (SELECT 1 FROM sys.database_principals
               WHERE name = N'qc_data_manager_role' AND type = 'R')
    CREATE ROLE [qc_data_manager_role];

-- Read-only on everything in the qc schema (current and future objects).
GRANT SELECT ON SCHEMA::[qc] TO [qc_data_manager_role];

/* --- controlled write path: grant EXECUTE per stored procedure LATER, as a
 * new migration once the procedures exist. Do NOT edit this file to add them.
 * Example (in e.g. 006_grant_execute_qc_procs.sql):
 *   GRANT EXECUTE ON OBJECT::[qc].[usp_insert_ph_log] TO [qc_data_manager_role];
 */

IF NOT EXISTS (SELECT 1 FROM [qc].[schema_migrations]
               WHERE filename = N'002_create_role_qc_data_manager.sql')
    INSERT INTO [qc].[schema_migrations] (filename)
    VALUES (N'002_create_role_qc_data_manager.sql');
GO
